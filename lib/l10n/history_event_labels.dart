/// 是否为已收录的历史事件码（用于区分「0–1 大端事件头」与「0–3 时间戳」误读）
bool isRecognizedHistoryEventCode(int code) => _zh.containsKey(code);

/// 历史记录事件类型（与固件 `record.h` 中 RC_* 及 BLE 行内 u16 LE 一致）
String historyEventDisplayName(int code, {required bool chinese}) {
  final m = chinese ? _zh : _en;
  final hex = '0x${code.toRadixString(16).toUpperCase().padLeft(4, '0')}';
  return m[code] ?? (chinese ? '未知 ($hex)' : 'Unknown ($hex)');
}

